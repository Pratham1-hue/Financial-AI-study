# Batch 2: the flood. Curated primary sources, verified by scripts/check_links.py.
# Merged with URL-level de-duplication so a resource never appears twice.
# ---------------------------------------------------------------------------
ALIASES = {}


def _merge_extra():
    try:
        from lib.res_finance import FINANCE
        from lib.res_ai import AI
        from lib.res_career import CAREER, RESEARCH
    except Exception:  # pragma: no cover - never break the app over extras
        return
    by_url = {}
    for key, v in RESOURCES.items():
        by_url[_norm_url(v.get("url", ""))] = key
    for extra in (FINANCE, AI, CAREER, RESEARCH):
        for key, val in extra.items():
            u = _norm_url(val.get("url", ""))
            if not u or key in RESOURCES:
                continue
            if u in by_url:
                # same URL already curated under another key - point at the original
                ALIASES[key] = by_url[u]
                continue
            RESOURCES[key] = val
            by_url[u] = key


def _norm_url(url):
    u = (url or "").strip().lower()
    for pre in ("https://", "http://"):
        if u.startswith(pre):
            u = u[len(pre):]
    if u.startswith("www."):
        u = u[4:]
    return u.rstrip("/")


_merge_extra()


